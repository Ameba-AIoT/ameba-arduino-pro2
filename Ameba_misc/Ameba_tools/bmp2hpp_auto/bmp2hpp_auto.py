#!/usr/bin/env python3
"""Convert the first/largest .bmp beside a sketch into an RGB565 header.

Invoked by the AmebaPro2 prebuild hook so a sketch can
just drop a .bmp next to it and #include "auto_bitmap.h".

Writes <sketch>/auto_bitmap.h containing:
    #define AUTO_BITMAP_WIDTH  ...
    #define AUTO_BITMAP_HEIGHT ...
    #define AUTO_BITMAP_NAME   "..."
    static const unsigned short auto_bitmap[W*H] PROGMEM = { ... };

The pixels are stored top-to-bottom, high byte first in the 16-bit value (the
normal RGB565 numeric form). AmebaILI9341::drawBitmap() does its own byte swap
for the SPI FIFO, so do not pre-swap here.

Re-runs only when a .bmp is newer than the generated header.
"""
import re
import struct
import sys
from pathlib import Path

OUT_NAME = "auto_bitmap.h"
ARRAY_NAME = "auto_bitmap"

# Emitted when there is no .bmp, so __has_include() alone cannot tell the two
# cases apart. AUTO_BITMAP_PRESENT lets the sketch distinguish "no image" from
# "converted image" without relying on the file existing.
STUB_HEADER = """\
// Generated by bmp2hpp_auto.py: no .bmp found beside the sketch.
// Drop a .bmp here and rebuild to replace this file.
#pragma once

#define AUTO_BITMAP_PRESENT 0
#define AUTO_BITMAP_WIDTH   0
#define AUTO_BITMAP_HEIGHT  0
#define AUTO_BITMAP_NAME    "(none)"
"""


def error_header(name):
    return f"""\
// Generated by bmp2hpp_auto.py: could not convert {name}.
// See the build log; this stub keeps the sketch compiling.
#pragma once

#define AUTO_BITMAP_PRESENT 0
#define AUTO_BITMAP_WIDTH   0
#define AUTO_BITMAP_HEIGHT  0
#define AUTO_BITMAP_NAME    "{name} (conversion failed)"
"""


def write_if_changed(path, text):
    """Avoid touching the file so the sketch is not needlessly recompiled."""
    try:
        if path.exists() and path.read_text(encoding="utf-8") == text:
            return
        path.write_text(text, encoding="utf-8")
    except OSError as exc:
        print(f"[bmp2hpp_auto] cannot write {path}: {exc}", file=sys.stderr)


def fail(msg):
    print(f"[bmp2hpp_auto] {msg}", file=sys.stderr)
    return False


def convert(bmp_path: Path, out_path: Path) -> bool:
    data = bmp_path.read_bytes()

    if data[:2] != b"BM":
        return fail(f"{bmp_path.name}: not a BMP") or False
    if len(data) < 54:
        return fail(f"{bmp_path.name}: truncated header") or False

    data_offset = struct.unpack_from("<I", data, 10)[0]
    header_size = struct.unpack_from("<I", data, 14)[0]
    if header_size < 40 or len(data) < 14 + header_size:
        return fail(f"{bmp_path.name}: unsupported/truncated header") or False

    width = struct.unpack_from("<i", data, 18)[0]
    height = struct.unpack_from("<i", data, 22)[0]
    bpp = struct.unpack_from("<H", data, 28)[0]
    compression = struct.unpack_from("<I", data, 30)[0]

    if bpp not in (16, 24, 32):
        return fail(f"{bmp_path.name}: {bpp}-bit not supported (use 16/24/32)") or False
    if compression not in (0, 3):
        return fail(f"{bmp_path.name}: compression {compression} not supported") or False
    if width <= 0 or height == 0:
        return fail(f"{bmp_path.name}: invalid dimensions") or False

    top_down = height < 0
    height = abs(height)

    if width > 240 or height > 320:
        return fail(f"{bmp_path.name}: {width}x{height} exceeds the 240x320 panel") or False

    bytes_per_pixel = bpp // 8
    stride = (width * bytes_per_pixel + 3) // 4 * 4
    pixels = data[data_offset:]
    if len(pixels) < stride * height:
        return fail(f"{bmp_path.name}: truncated pixel data") or False

    # 16-bit BMPs are RGB555 unless BI_BITFIELDS supplies explicit masks.
    masks = (0x7C00, 0x03E0, 0x001F)
    if bpp == 16 and compression == 3:
        if len(data) < 66:
            return fail(f"{bmp_path.name}: truncated color masks") or False
        masks = struct.unpack_from("<III", data, 54)
    channels = []
    used = 0
    for mask in masks:
        if not mask or mask > 0xFFFF or mask & used:
            return fail(f"{bmp_path.name}: invalid color masks") or False
        shift = (mask & -mask).bit_length() - 1
        maximum = mask >> shift
        if maximum & (maximum + 1):
            return fail(f"{bmp_path.name}: non-contiguous mask") or False
        channels.append((mask, shift, maximum))
        used |= mask

    rows = range(height) if top_down else range(height - 1, -1, -1)
    out = []
    for y in rows:
        row = y * stride
        for x in range(width):
            i = row + x * bytes_per_pixel
            if bpp == 16:
                v = struct.unpack_from("<H", pixels, i)[0]
                r5, g6, b5 = (
                    (((v & m) >> s) * target + mx // 2) // mx
                    for (m, s, mx), target in zip(channels, (31, 63, 31))
                )
            elif bpp == 24:
                b, g, r = pixels[i], pixels[i + 1], pixels[i + 2]
                r5, g6, b5 = r >> 3, g >> 2, b >> 3
            else:
                b, g, r = pixels[i], pixels[i + 1], pixels[i + 2]
                r5, g6, b5 = r >> 3, g >> 2, b >> 3
            out.append((r5 << 11) | (g6 << 5) | b5)

    lines = [
        "// Generated by bmp2hpp_auto.py from " + bmp_path.name,
        "// Do not edit; rebuilt automatically when the .bmp changes.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "#define AUTO_BITMAP_PRESENT 1",
        f"#define AUTO_BITMAP_WIDTH  {width}",
        f"#define AUTO_BITMAP_HEIGHT {height}",
        f'#define AUTO_BITMAP_NAME   "{bmp_path.name}"',
        "",
        f"static const unsigned short {ARRAY_NAME}[{width * height}] PROGMEM = {{",
    ]
    for start in range(0, len(out), 8):
        lines.append("    " + ", ".join(f"0x{p:04X}" for p in out[start:start + 8]) + ",")
    lines.append("};")
    lines.append("")

    write_if_changed(out_path, "\n".join(lines))
    print(f"[bmp2hpp_auto] {bmp_path.name} -> {out_path.name} ({width}x{height})")
    return True


def main():
    if len(sys.argv) < 2:
        print("[bmp2hpp_auto] usage: bmp2hpp_auto.py <sketch_dir> [build_sketch_dir]", file=sys.stderr)
        return 2
    sketch = Path(sys.argv[1])
    if not sketch.is_dir():
        print(f"[bmp2hpp_auto] not a directory: {sketch}", file=sys.stderr)
        return 2

    # Arduino compiles from a copy of the sketch under {build.path}/sketch, so
    # the generated header has to exist there too. The build copy is made before
    # prebuild hooks run, hence the explicit second write.
    targets = [sketch / OUT_NAME]
    if len(sys.argv) > 2:
        build_sketch = Path(sys.argv[2])
        # The build's sketch copy may not exist yet when prebuild hooks run.
        try:
            build_sketch.mkdir(parents=True, exist_ok=True)
            targets.append(build_sketch / OUT_NAME)
        except OSError as exc:
            print(f"[bmp2hpp_auto] cannot prepare {build_sketch}: {exc}", file=sys.stderr)

    bmps = sorted(sketch.glob("*.bmp"))
    if not bmps:
        # Write a stub rather than deleting the header. The Arduino builder
        # collects this sketch's files *before* prebuild hooks run, so removing
        # the file here makes that copy step fail with "unable to read contents
        # of the source item".
        for out in targets:
            write_if_changed(out, STUB_HEADER)
        return 0

    # Prefer the largest image; ties go to the first name alphabetically.
    bmp = max(bmps, key=lambda p: (p.stat().st_size, p.name))
    try:
        for out in targets:
            if not convert(bmp, out):
                # Keep the build compiling even if the image is unusable.
                write_if_changed(out, error_header(bmp.name))
                return 1
        return 0
    except Exception as exc:  # keep the build going with a clear message
        print(f"[bmp2hpp_auto] {bmp.name}: {exc}", file=sys.stderr)
        for out in targets:
            write_if_changed(out, error_header(bmp.name))
        return 1


if __name__ == "__main__":
    sys.exit(main())
